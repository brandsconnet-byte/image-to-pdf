export function getTranslation(lang: LanguageCode | string = 'en', key: string): string {
  const code = ((lang && lang in translations) ? lang : 'en') as LanguageCode;
  const dict = translations[code] || translations.en;
  return dict[key] || translations.en[key] || key;
}
